-- Journal des offres lues puis écartées sans candidature (démarche de recherche).
-- motif_ecart : 1 = profil, 2 = poste, 3 = distance (enum MotifEcart).
CREATE TABLE offre_consultee (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    titulaire         VARCHAR(16)   NOT NULL,
    date_consultation DATE          NOT NULL,
    intitule          VARCHAR(255)  NOT NULL,
    entreprise        VARCHAR(255)  NOT NULL,
    lien              VARCHAR(1000) NULL,
    motif_ecart       INTEGER       NOT NULL,
    commentaire       VARCHAR(1000) NULL,
    CONSTRAINT pk_offre_consultee PRIMARY KEY (id)
);
CREATE INDEX idx_offre_consultee_titulaire_date ON offre_consultee (titulaire, date_consultation);
